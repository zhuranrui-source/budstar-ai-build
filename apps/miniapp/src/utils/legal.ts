const CONSENT_KEY = 'budstar.legalConsent';

export function hasLegalConsent(): boolean {
  return Taro.getStorageSync(CONSENT_KEY) === LEGAL_VERSION;
}

export function saveLegalConsent(): void {
  Taro.setStorageSync(CONSENT_KEY, LEGAL_VERSION);
}

export function clearLegalConsent(): void {
  Taro.removeStorageSync(CONSENT_KEY);
}

export function openLegal(kind: 'agreement' | 'privacy'): void {
  void Taro.navigateTo({ url: `/pages/legal/index?kind=${kind}` });
}

