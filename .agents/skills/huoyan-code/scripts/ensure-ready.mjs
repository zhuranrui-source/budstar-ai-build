#!/usr/bin/env node
/**
 * 静默环境准备：检查 Gateway Key → 合并 huoyan-code MCP 配置
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir, platform } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DEFAULT_MCP_MODULE_API_KEY,
  buildMcpSnippet,
  resolveMcpBaseUrl,
  resolveMcpHost,
} from './mcp-endpoint.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SKILL_ROOT = join(__dirname, '..');
const QUIET = process.argv.includes('--quiet');

function log(...args) {
  if (!QUIET) console.error(...args);
}

function parseMcpHostArg() {
  const idx = process.argv.indexOf('--mcp-host');
  if (idx >= 0 && process.argv[idx + 1]) return process.argv[idx + 1].trim();
  return undefined;
}

function npxBin() {
  return platform() === 'win32' ? 'npx.cmd' : 'npx';
}

function readTokens() {
  const envName = (process.env.OPPO_AGENT_ENV || 'prod').trim() || 'prod';
  const path = join(homedir(), '.oppo-agent', envName, 'tokens.json');
  try {
    return { path, data: JSON.parse(readFileSync(path, 'utf8')) };
  } catch {
    return { path, data: null };
  }
}

function readGatewayKey() {
  const fromEnv = process.env.OPPO_AGENT_GATEWAY_API_KEY?.trim();
  if (fromEnv) return fromEnv;
  try {
    return execFileSync(
      npxBin(),
      [
        '--yes',
        '--registry=http://admin.npm.oppoer.me',
        'oppo-agent-gateway',
        '-H',
        'show',
      ],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
    ).trim();
  } catch {
    return null;
  }
}

function runGatewayCreate() {
  log('需要 OPPO SSO 登录以创建 Gateway Key…');
  const r = spawnSync(
    npxBin(),
    [
      '--yes',
      '--registry=http://admin.npm.oppoer.me',
      'oppo-agent-gateway',
      'create',
    ],
    { stdio: QUIET ? 'pipe' : 'inherit', encoding: 'utf8' },
  );
  return r.status === 0;
}

function assertPersistableEnvValue(name, value) {
  const v = String(value ?? '');
  if (!v) throw new Error(`${name} is empty`);
  if (/[\r\n\0]/.test(v))
    throw new Error(`${name} contains illegal control characters`);
  return v;
}

function shellSingleQuote(value) {
  return `'${String(value).replace(/'/g, `'\"'\"'`)}'`;
}

function persistGatewayKey(gatewayKey) {
  const key = assertPersistableEnvValue(
    'OPPO_AGENT_GATEWAY_API_KEY',
    gatewayKey,
  );

  if (platform() === 'win32') {
    spawnSync(
      'powershell',
      [
        '-NoProfile',
        '-Command',
        "[Environment]::SetEnvironmentVariable('OPPO_AGENT_GATEWAY_API_KEY',$env:OX_GW_KEY,'User')",
      ],
      { stdio: 'ignore', env: { ...process.env, OX_GW_KEY: key } },
    );
  } else {
    const oppoDir = join(homedir(), '.oppo-agent');
    mkdirSync(oppoDir, { recursive: true });
    writeFileSync(
      join(oppoDir, 'huoyan-code-user-env.sh'),
      [
        '# generated by huoyan-code ensure-ready; do not edit',
        `export OPPO_AGENT_GATEWAY_API_KEY=${shellSingleQuote(key)}`,
        '',
      ].join('\n'),
      { encoding: 'utf8', mode: 0o600 },
    );
    const profile = existsSync(join(homedir(), '.zshrc'))
      ? join(homedir(), '.zshrc')
      : join(homedir(), '.bashrc');
    const marker = '# huoyan-code env';
    const sourceLine =
      '[ -f "$HOME/.oppo-agent/huoyan-code-user-env.sh" ] && . "$HOME/.oppo-agent/huoyan-code-user-env.sh"  # huoyan-code env';
    let content = existsSync(profile) ? readFileSync(profile, 'utf8') : '';
    if (!content.includes(marker)) {
      writeFileSync(profile, `${content}\n${marker}\n${sourceLine}\n`, 'utf8');
    }
  }
  process.env.OPPO_AGENT_GATEWAY_API_KEY = key;
}

function mergeMcpConfig(mcpHost, moduleApiKey) {
  const cursorDir = join(homedir(), '.cursor');
  const mcpPath = join(cursorDir, 'mcp.json');
  const snippet = buildMcpSnippet(mcpHost, moduleApiKey);
  let config = { mcpServers: {} };
  if (existsSync(mcpPath)) {
    try {
      config = JSON.parse(readFileSync(mcpPath, 'utf8'));
      if (!config.mcpServers || typeof config.mcpServers !== 'object') {
        config.mcpServers = {};
      }
    } catch {
      config = { mcpServers: {} };
    }
  } else {
    mkdirSync(cursorDir, { recursive: true });
  }
  const before = JSON.stringify(config.mcpServers['huoyan-code'] ?? null);
  config.mcpServers['huoyan-code'] = snippet['huoyan-code'];
  const after = JSON.stringify(config.mcpServers['huoyan-code']);
  const changed = before !== after;
  if (changed) {
    writeFileSync(mcpPath, `${JSON.stringify(config, null, 2)}\n`, 'utf8');
  }
  const snippetPath = join(
    SKILL_ROOT,
    'references',
    'generated-mcp-snippet.json',
  );
  writeFileSync(
    snippetPath,
    `${JSON.stringify({ mcpServers: snippet }, null, 2)}\n`,
    'utf8',
  );
  return { mcpPath, changed };
}

function assess() {
  const tokens = readTokens();
  const userId =
    process.env.OPPO_AGENT_USER_ID?.trim() ||
    tokens.data?.userId?.trim() ||
    null;
  const gatewayKey = readGatewayKey();
  const mcpPath = join(homedir(), '.cursor', 'mcp.json');
  let hasMcpEntry = false;
  if (existsSync(mcpPath)) {
    try {
      const cfg = JSON.parse(readFileSync(mcpPath, 'utf8'));
      hasMcpEntry = Boolean(cfg?.mcpServers?.['huoyan-code']?.url);
    } catch {
      hasMcpEntry = false;
    }
  }
  return {
    tokensOk: Boolean(tokens.data),
    userId,
    gatewayKey,
    hasMcpEntry,
    envKeyOk: Boolean(process.env.OPPO_AGENT_GATEWAY_API_KEY?.trim()),
    ready: Boolean(gatewayKey && hasMcpEntry),
  };
}

const mcpHost = resolveMcpHost(parseMcpHostArg());
const mcpBaseUrl = resolveMcpBaseUrl(mcpHost);
const moduleApiKey =
  process.env.HUOYAN_CODE_MCP_MODULE_API_KEY?.trim() ||
  DEFAULT_MCP_MODULE_API_KEY;
const actions = [];
let needsSso = false;
let needsCursorRestart = false;

let state = assess();

if (!state.gatewayKey) {
  needsSso = true;
  const created = runGatewayCreate();
  actions.push(created ? 'gateway_create' : 'gateway_create_failed');
  state = assess();
}

if (state.gatewayKey && !state.envKeyOk) {
  try {
    persistGatewayKey(state.gatewayKey);
    actions.push('persist_gateway_key');
    needsCursorRestart = true;
  } catch (e) {
    actions.push('persist_gateway_key_failed');
    log(
      'persist_gateway_key failed:',
      e instanceof Error ? e.message : String(e),
    );
  }
  state = assess();
}

if (state.gatewayKey) {
  const merge = mergeMcpConfig(mcpHost, moduleApiKey);
  actions.push(merge.changed ? 'merge_mcp_config' : 'mcp_config_up_to_date');
  if (merge.changed) needsCursorRestart = true;
  state = assess();
}

const result = {
  ok: Boolean(state.gatewayKey && state.hasMcpEntry),
  userId: state.userId,
  needsCursorRestart,
  needsSso,
  actions,
  mcpHost,
  mcpBaseUrl,
  hint: null,
};

if (!result.ok) {
  if (!state.gatewayKey) {
    result.hint = '无法获取 Gateway Key，请在浏览器完成 OPPO SSO 登录后重试';
  } else if (!state.hasMcpEntry) {
    result.hint = '无法写入 ~/.cursor/mcp.json，请检查文件权限';
  }
} else if (needsCursorRestart) {
  result.hint =
    '已更新本机凭证或 MCP 配置。请完全退出并重启 Agent 客户端一次；重启前可继续对话，但 MCP 需重启后才生效。';
}

console.log(JSON.stringify(result, null, 2));
process.exit(result.ok ? 0 : 1);
